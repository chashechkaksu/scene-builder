import type { SemanticWeightedTerm } from '@/shared/types'

type Weight = SemanticWeightedTerm['weight']

export interface ObjectSemantics {
  objectId: string
  terms: SemanticWeightedTerm[]
}

function terms(literal: string[], strong: string[], associative: string[]): SemanticWeightedTerm[] {
  const withWeight =
    (weight: Weight) =>
    (text: string): SemanticWeightedTerm => ({ text, weight })
  return [
    ...literal.map(withWeight('literal')),
    ...strong.map(withWeight('strong')),
    ...associative.map(withWeight('associative')),
  ]
}

